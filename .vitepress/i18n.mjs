export function interfaceText(code) {
	return {...texts.en, ...texts[code]};
}

// Texts of the search box, in the format of the VitePress local search.
export function searchTranslations(code) {
	const text = interfaceText(code);

	return {
		button: {buttonText: text.search, buttonAriaLabel: text.search},
		modal: {
			displayDetails: text.details,
			resetButtonTitle: text.reset,
			backButtonTitle: text.close,
			noResultsText: text.noResults,
			footer: {selectText: text.select, navigateText: text.navigate, closeText: text.exit},
		},
	};
}
